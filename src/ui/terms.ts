const BY_ID = new Map(GLOSSARY.map((t) => [t.id, t]))

/** Формы, отсортированные от длинных к коротким: «шансы банка» должно
 *  выигрывать у «банка», иначе ссылка встанет на половину словосочетания. */
const SORTED: Array<{ form: string; id: string }> = Object.entries(FORMS)
  .flatMap(([id, forms]) => forms.map((form) => ({ form, id })))
  .filter(({ id }) => BY_ID.has(id))
  .sort((a, b) => b.form.length - a.form.length)

export const termById = (id: string): GlossaryTerm | undefined => BY_ID.get(id)

const isWordChar = (ch: string | undefined): boolean =>
  ch !== undefined && /[0-9a-zа-яё]/i.test(ch)

export type Segment = { text: string; id?: string }

/**
 * Разбивает текст на куски, отмечая известные термины. Каждый термин
 * отмечается только при первом появлении — иначе подчёркнутым окажется
 * пол-абзаца.
 *
 * `seen` можно передать снаружи и переиспользовать между строками: список
 * причин в «Разборе» — это несколько строк, но читается он как один блок,
 * и «колл» подчёркнутый в каждой второй строке выглядит неряшливо.
 */
export function linkTerms(text: string, seen: Set<string> = new Set()): Segment[] {
  const segments: Segment[] = []
  const lower = text.toLowerCase()
  let plain = ''
  let i = 0

  while (i < text.length) {
    let matched: { form: string; id: string } | null = null
    for (const candidate of SORTED) {
      if (seen.has(candidate.id)) continue
      if (!lower.startsWith(candidate.form, i)) continue
      // Границы слова: буквы и цифры по краям означают, что мы попали
      // в середину другого слова.
      if (isWordChar(text[i - 1])) continue
      if (isWordChar(text[i + candidate.form.length])) continue
      matched = candidate
      break
    }
    if (matched) {
      if (plain) { segments.push({ text: plain }); plain = '' }
      segments.push({ text: text.slice(i, i + matched.form.length), id: matched.id })
      seen.add(matched.id)
      i += matched.form.length
    } else {
      plain += text[i]
      i += 1
    }
  }
  if (plain) segments.push({ text: plain })
  return segments
}
